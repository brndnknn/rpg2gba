"""Corpus census -> `rpg2gba_sizes.gen.h` (synthetic maps, no `output/` needed)."""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from rpg2gba.game_profile import census as c
from rpg2gba.map_split.ids import piece_uid

SWITCHES = {1: "Got Starter", 2: "s:tsOn?(\"A\")", 3: "s:pbIsWeekday(1)", 4: "Beat Gym"}
VARIABLES = {1: "Counter", 2: "Steps", 3: ""}


def _script(code: int, text: str) -> dict:
    return {"code": code, "indent": 0, "parameters": [text]}


def _page(cmds: list[dict], cond: dict | None = None) -> dict:
    return {"condition": cond or {}, "list": cmds}


def _route(target: int, opacity: int) -> dict:
    return {
        "code": 209,
        "indent": 0,
        "parameters": [target, {"list": [{"code": 42, "parameters": [opacity]}, {"code": 0}]}],
    }


def _event(eid: int, pages: list[dict]) -> dict:
    return {"id": eid, "pages": pages}


def _write(tmp_path: Path, maps: list[dict], trainers: int = 3) -> Path:
    build = tmp_path / "build"
    (build / "maps").mkdir(parents=True)
    for m in maps:
        (build / "maps" / f"Map{m['map_id']:03d}.json").write_text(json.dumps(m), encoding="utf-8")
    (build / "intermediate").mkdir()
    (build / "intermediate" / "trainers.json").write_text(
        json.dumps({"trainers": {f"T{i}": {} for i in range(trainers)}}), encoding="utf-8"
    )
    return build


def _refs(tmp_path: Path) -> tuple[Path, Path]:
    sw, var = tmp_path / "sw.json", tmp_path / "var.json"
    sw.write_text(json.dumps({str(k): v for k, v in SWITCHES.items()}), encoding="utf-8")
    var.write_text(json.dumps({str(k): v for k, v in VARIABLES.items()}), encoding="utf-8")
    return sw, var


def _maps() -> list[dict]:
    return [
        {
            "map_id": 5,
            "events": [
                _event(1, [
                    _page([_script(355, 'setTempSwitchOn("a")'), {"code": 123, "parameters": ["A", 0]}]),
                    _page([], {"self_switch_valid": True, "self_switch_ch": "B"}),
                ]),
                _event(2, [
                    _page(
                        [_script(355, 'pbSetSelfSwitch(7,"A",true)'), _route(9, 0)],
                        {"switch1_valid": True, "switch1_id": 2},
                    ),
                    _page([
                        _script(355, "for i in 10..12"),
                        _script(655, 'pbSetSelfSwitch(i,"C",true)'),
                        _script(655, "end"),
                        _route(0, 0),
                        _route(-1, 0),
                    ]),
                ]),
            ],
        },
        # Two pieces of origin map 5: every key must collapse onto the origin.
        {
            "map_id": piece_uid(5, 1),
            "events": [_event(1, [_page([_script(355, 'setTempSwitchOn("A")'),
                                        {"code": 123, "parameters": ["A", 0]}])])],
        },
        {"map_id": 6, "events": [_event(1, [_page([{"code": 123, "parameters": ["A", 0]}])])]},
    ]


def test_collect_keys_collapses_split_origin_and_finds_every_form() -> None:
    temp, selfsw, hide = c.collect_keys(_maps(), SWITCHES)
    # EV1 setTempSwitchOn("a") (case-folded) merged with the piece's "A"; EV2 reads tsOn?("A").
    assert temp == {(5, 1, "A"), (5, 2, "A")}
    assert selfsw == {
        (5, 1, "A"), (5, 1, "B"),           # code 123 + page condition
        (5, 7, "A"),                        # pbSetSelfSwitch cross-event
        (5, 10, "C"), (5, 11, "C"), (5, 12, "C"),  # fused for-loop
        (6, 1, "A"),
    }
    assert hide == {(5, 9), (5, 2)}         # target 9, and 0 = the scripting event; player excluded


def test_census_counts_and_ceil8_capacities(tmp_path: Path) -> None:
    build = _write(tmp_path, _maps(), trainers=5)
    sw, var = _refs(tmp_path)
    cen = c.build_census(build, sw, var)
    assert cen == c.EventCensus(
        temp_switches=2, global_switches=2, self_switches=7, hide_flags=2, vars=2, trainers=5
    )
    assert c.capacities(cen) == {
        "tempswitches": 8, "flags": 8, "selfswitches": 16, "vars": 8, "trainers": 5,
    }


@pytest.mark.parametrize("n,expected", [(0, 0), (1, 8), (8, 8), (9, 16), (1170, 1176)])
def test_ceil8(n: int, expected: int) -> None:
    assert c._ceil8(n) == expected


GOLDEN = """// DO NOT EDIT — generated by rpg2gba.game_profile.census
// source: output/uranium-build/maps/Map*.json + intermediate/trainers.json + reference/uranium_switches.json + uranium_variables.json
#ifndef GUARD_CONFIG_RPG2GBA_SIZES_GEN_H
#define GUARD_CONFIG_RPG2GBA_SIZES_GEN_H

// Whole-corpus demand (not per chapter, so the save layout never moves between
// chapters): 2 temp, 2 global, 7 self + 2 hide (shared region), 2 vars, 5 trainers.
// Flag regions and vars are the demand rounded up to a multiple of 8.
#define RPG2GBA_TEMP_FLAGS_COUNT       8
#define RPG2GBA_GLOBAL_FLAGS_COUNT     8
#define RPG2GBA_SELFSWITCH_FLAGS_COUNT 16
#define RPG2GBA_VARS_COUNT             8
// Generated trainer ids chain from TRAINER_MAY_PLACEHOLDER (constants/opponents.h).
#define RPG2GBA_GAME_TRAINERS_COUNT    5

#endif // GUARD_CONFIG_RPG2GBA_SIZES_GEN_H
"""


def test_header_golden_and_idempotent_install(tmp_path: Path) -> None:
    build = _write(tmp_path, _maps(), trainers=5)
    sw, var = _refs(tmp_path)
    fork = tmp_path / "fork"
    rel = c.install(fork, build, sw, var)
    dest = fork / rel
    assert rel == Path("include/config/rpg2gba_sizes.gen.h")
    assert dest.read_text(encoding="utf-8") == GOLDEN
    mtime = dest.stat().st_mtime_ns
    c.install(fork, build, sw, var)
    assert dest.read_text(encoding="utf-8") == GOLDEN
    assert dest.stat().st_mtime_ns == mtime  # byte-stable: not rewritten


def test_missing_maps_fail_loud(tmp_path: Path) -> None:
    (tmp_path / "maps").mkdir()
    with pytest.raises(FileNotFoundError):
        c.load_maps(tmp_path / "maps")
