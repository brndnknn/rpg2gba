"""item_converter.bag: generated pocket sizes and secret-base capacity."""
from __future__ import annotations

from pathlib import Path

import pytest

from rpg2gba.item_converter import bag
from rpg2gba.pbs_converter.items import Item


def _rec(pocket: int, n: int) -> list[Item]:
    return [Item(id=i, pocket=pocket, price=0, item_use=0, battle_use=0,
                 item_type=0, machine_move=0) for i in range(n)]


def test_counts_map_through_fork_pockets() -> None:
    recs = _rec(8, 100) + _rec(4, 108) + _rec(1, 5) + _rec(2, 3)
    counts = bag.pocket_kind_counts(recs)
    assert counts["POCKET_KEY_ITEMS"] == 100
    assert counts["POCKET_TM_HM"] == 108
    assert counts["POCKET_ITEMS"] == 8  # medicine folds into items
    assert bag.pocket_sizes(counts) == (100, 108)


def test_never_below_stock() -> None:
    counts = bag.pocket_kind_counts(_rec(8, 3) + _rec(4, 10))
    assert bag.pocket_sizes(counts) == (30, 64)
    assert bag.pocket_sizes({}) == (30, 64)


def test_save_delta_estimate() -> None:
    assert bag.save_delta_bytes(100, 108, 1) == (70 + 44) * 4 - 19 * 160
    assert bag.save_delta_bytes(30, 64, 20) == 0


def test_header_golden() -> None:
    assert bag.render_bag(100, 108, secret_bases=1) == (
        "// Generated by rpg2gba (item_converter.bag) -- do not edit.\n"
        "// Bag pocket sizes = max(stock, the game's own item kinds per pocket);\n"
        "// secret-base capacity is a profile decision (the game has none).\n"
        "#ifndef GUARD_RPG2GBA_BAG_GEN_H\n"
        "#define GUARD_RPG2GBA_BAG_GEN_H\n"
        "#define RPG2GBA_BAG_KEYITEMS_COUNT 100\n"
        "#define RPG2GBA_BAG_TMHM_COUNT 108\n"
        "#define RPG2GBA_SECRET_BASES_COUNT 1\n"
        "#endif\n"
    )


def test_render_is_idempotent() -> None:
    assert bag.render_bag(100, 108, secret_bases=1) == bag.render_bag(100, 108, secret_bases=1)


def test_zero_secret_bases_refused() -> None:
    with pytest.raises(ValueError):
        bag.render_bag(30, 64, secret_bases=0)


def test_stage_writes_header_idempotently(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(bag.pbs_items, "parse", lambda _p: _rec(8, 100) + _rec(4, 108))
    a = bag.render_for_game(tmp_path)
    b = bag.render_for_game(tmp_path)
    assert a == b and "KEYITEMS_COUNT 100" in a and "TMHM_COUNT 108" in a
