"""Id-remapped scrolling connections between maps on different tilesets (design R).

The engine's ``FillConnection`` (engine/src/fieldmap.c) copies a neighbour's raw
metatile ids into the current map's backup grid and draws them through the CURRENT
map's tileset. Two maps on different RMXP tilesets therefore can't share ids. Design R
(operator-approved 2026-10-06, ``reference/chapters/06-tileset-plan.md``): each map
keeps its own tileset, the build imports the neighbour's border-strip art into it,
and a generated per-direction table translates every neighbour id seen in the strip
to the current map's id holding the same art. The engine side
(``engine/src/uranium_connection_remap.c``, plus the ``FillConnection`` /
``CameraMove`` hooks in ``fieldmap.c`` and ``LoadMapFromCameraTransition`` in
``overworld.c``) applies the table while copying the strip and reloads the full
tileset on crossing.

This module owns the pure parts:

- `RemapDirection` + `remap_directions`: one direction per side of each remapped
  `connections.ConnectionRow`, in pokeemerald offset convention.
- `strip_cells`: the neighbour cells the engine copies within `depth` of the shared
  edge, mirroring `FillNorth/South/West/EastConnection`'s clipping exactly.
- `source_key` / `composite_key`: art identity for "does cur already hold this?".
- `build_remap_table`: neighbour id -> current id (current void elsewhere).
- `render_remap_header` / `write_remap_header`: the
  ``src/data/uranium_connection_remaps.gen.h`` fragment (stub when no remaps).
"""
from __future__ import annotations

import logging
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from rpg2gba.tileset_converter.tile_map import NUM_METATILES_TOTAL

logger = logging.getLogger(__name__)

# engine/include/fieldmap.h: MAP_OFFSET (rows/cols copied from a neighbour; east 8).
MAP_OFFSET = 7
# Rows/columns of the neighbour that must render right, per axis (field_camera.c,
# verified 2026-10-07): the player sees 5 cells up/down (the 5th half-visible) and 7
# left/right, and CameraMove switches maps before the next row draws, so no extra
# scroll row is needed. Operator-approved 2026-10-09, replacing a uniform 6.
STRIP_DEPTH_NS = 5
STRIP_DEPTH_EW = 7

GEN_RELPATH = Path("src/data/uranium_connection_remaps.gen.h")
_GEN_HEADER = "// generated by rpg2gba — do not edit\n"

_DIRECTIONS = ("up", "down", "left", "right")


@dataclass(frozen=True)
class RemapDirection:
    """`cur` sees `nbr` across its `direction` edge; `offset` is cur's pokeemerald
    connection offset (``connections.build_connections`` convention)."""

    cur: int
    nbr: int
    direction: str
    offset: int


def remap_directions(rows: Iterable) -> list[RemapDirection]:
    """Both directions of every remapped `ConnectionRow`, sorted (cur, nbr)."""
    from rpg2gba.tileset_converter.connections import EDGE_TO_DIRECTION

    out: list[RemapDirection] = []
    for row in rows:
        off_a = row.offset_a - row.offset_b
        out.append(RemapDirection(row.map_a, row.map_b, EDGE_TO_DIRECTION[row.edge_a], off_a))
        out.append(RemapDirection(row.map_b, row.map_a, EDGE_TO_DIRECTION[row.edge_b], -off_a))
    return sorted(out, key=lambda d: (d.cur, d.nbr))


def _span(offset: int, cur_len: int, nbr_len: int) -> tuple[int, int]:
    """(first neighbour index, count) along the edge — the shared x/y clipping of
    fieldmap.c Fill*Connection against a backup grid of cur_len + 2*7 + 1."""
    backup = cur_len + 2 * MAP_OFFSET + 1
    pos = offset + MAP_OFFSET
    if pos < 0:
        start = -pos
        pos += nbr_len
        count = pos if pos < backup else backup
    else:
        start = 0
        count = nbr_len if pos + nbr_len < backup else backup - pos
    return start, max(0, min(count, nbr_len - start))


def strip_depth(direction: str) -> int:
    """The visible strip depth for a connection `direction`: N/S 5, E/W 7."""
    if direction not in _DIRECTIONS:
        raise ValueError(f"unknown connection direction {direction!r}")
    return STRIP_DEPTH_NS if direction in ("up", "down") else STRIP_DEPTH_EW


def strip_cells(
    cur_w: int, cur_h: int, nbr_w: int, nbr_h: int,
    direction: str, offset: int, depth: int | None = None,
) -> list[tuple[int, int]]:
    """Neighbour-local (x, y) cells the engine copies into cur's grid, limited to the
    `depth` rows/columns nearest the shared edge (default: `strip_depth(direction)`).
    Row-major, deterministic."""
    if direction not in _DIRECTIONS:
        raise ValueError(f"unknown connection direction {direction!r}")
    if depth is None:
        depth = strip_depth(direction)
    if not 1 <= depth <= MAP_OFFSET:
        raise ValueError(f"strip depth {depth} outside 1..{MAP_OFFSET}")
    if direction in ("up", "down"):
        start, count = _span(offset, cur_w, nbr_w)
        xs = range(start, start + count)
        ys = range(max(0, nbr_h - depth), nbr_h) if direction == "up" else range(min(depth, nbr_h))
    else:
        start, count = _span(offset, cur_h, nbr_h)
        ys = range(start, start + count)
        xs = range(max(0, nbr_w - depth), nbr_w) if direction == "left" else range(min(depth, nbr_w))
    return [(x, y) for y in ys for x in xs]


def _norm(img: np.ndarray) -> bytes:
    a = np.asarray(img, dtype=np.uint8).copy()
    a[a[..., 3] == 0] = 0
    return a.tobytes()


def _composite(bottom: np.ndarray, top: np.ndarray) -> bytes:
    b = np.asarray(bottom, dtype=np.float32) / 255.0
    t = np.asarray(top, dtype=np.float32) / 255.0
    ta = t[..., 3:4]
    ba = b[..., 3:4]
    oa = ta + ba * (1 - ta)
    rgb = np.where(oa > 0, (t[..., :3] * ta + b[..., :3] * ba * (1 - ta)) / np.maximum(oa, 1e-6), 0)
    out = np.concatenate([rgb, oa], axis=-1)
    return _norm(np.round(out * 255).astype(np.uint8))


def source_key(mt) -> tuple:
    """Pre-quantization layered art identity: (bottom, top, every frame), with RGB
    under fully transparent pixels zeroed. Behavior / layer type excluded."""
    return (
        _norm(mt.bottom), _norm(mt.top),
        tuple((_norm(b), _norm(t)) for b, t in (mt.frames or [])),
    )


def composite_key(mt) -> tuple:
    """Pre-quantization COMPOSED art identity (bottom under top, all frames): matches
    the same picture even when the two tilesets split it across layers differently."""
    return (
        _composite(mt.bottom, mt.top),
        tuple(_composite(b, t) for b, t in (mt.frames or [])),
    )


def build_remap_table(
    strip_nbr_ids: Iterable[int],
    cur_id_of_nbr: Mapping[int, int],
    void_id: int,
) -> list[int]:
    """Neighbour id -> cur id for EVERY id in `cur_id_of_nbr` (any neighbour metatile
    whose art the current tileset holds — the engine also runs the screen the player
    just saw through the new map's table on crossing); `void_id` elsewhere. Fails
    loud if a strip id has no cur id or an id is out of range."""
    table = [void_id] * NUM_METATILES_TOTAL
    for nid, cid in sorted(cur_id_of_nbr.items()):
        if not 0 <= nid < NUM_METATILES_TOTAL:
            raise ValueError(f"neighbour metatile id {nid} out of range")
        if not 0 <= cid < NUM_METATILES_TOTAL:
            raise ValueError(f"current metatile id {cid} out of range")
        table[nid] = cid
    for nid in sorted(set(strip_nbr_ids)):
        if nid not in cur_id_of_nbr:
            raise KeyError(f"strip metatile {nid} has no current-tileset id")
    return table


def check_both_directions(directions: Iterable[RemapDirection]) -> None:
    """Every remapped seam needs both directions (the engine rewrites the old view
    through the new map's table on crossing). Fails loud on a one-sided seam."""
    pairs = {(d.cur, d.nbr) for d in directions}
    lonely = sorted(p for p in pairs if (p[1], p[0]) not in pairs)
    if lonely:
        raise ValueError(f"remapped connection(s) missing their reverse direction: {lonely}")


@dataclass(frozen=True)
class RemapTable:
    cur: int
    nbr: int
    table: list[int]


def _ident(cur: int, nbr: int) -> str:
    return f"sUraniumConnRemap_{cur:03d}_{nbr:03d}"


def render_remap_header(
    tables: list[RemapTable], map_const_of: Callable[[int], str] | None = None
) -> str:
    """The gen-header text. No tables -> the compile-only stub."""
    if not tables:
        return (
            _GEN_HEADER
            + "#define URANIUM_CONNECTION_REMAP_COUNT 0\n"
            + "static const struct UraniumConnectionRemap sUraniumConnectionRemaps[] = { {0} };\n"
        )
    if map_const_of is None:
        raise ValueError("remapped connections need map_const_of to name MAP_* constants")
    parts = [_GEN_HEADER, f"#define URANIUM_CONNECTION_REMAP_COUNT {len(tables)}\n"]
    for t in sorted(tables, key=lambda t: (t.cur, t.nbr)):
        if len(t.table) != NUM_METATILES_TOTAL:
            raise ValueError(f"remap {t.cur}->{t.nbr}: table length {len(t.table)}")
        parts.append(f"static const u16 {_ident(t.cur, t.nbr)}[NUM_METATILES_TOTAL] = {{\n")
        for i in range(0, NUM_METATILES_TOTAL, 16):
            parts.append("    " + ", ".join(str(v) for v in t.table[i:i + 16]) + ",\n")
        parts.append("};\n")
    parts.append("static const struct UraniumConnectionRemap sUraniumConnectionRemaps[] = {\n")
    for t in sorted(tables, key=lambda t: (t.cur, t.nbr)):
        c, n = map_const_of(t.cur), map_const_of(t.nbr)
        parts.append(
            f"    {{ .mapGroup = MAP_GROUP({c}), .mapNum = MAP_NUM({c}), "
            f".connGroup = MAP_GROUP({n}), .connNum = MAP_NUM({n}), "
            f".table = {_ident(t.cur, t.nbr)} }},\n"
        )
    parts.append("};\n")
    return "".join(parts)


def write_remap_header(
    engine_root: Path, tables: list[RemapTable],
    map_const_of: Callable[[int], str] | None = None,
) -> Path:
    """(Over)write the gen header under `engine_root` (idempotent, byte-stable)."""
    path = Path(engine_root) / GEN_RELPATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_remap_header(tables, map_const_of), encoding="utf-8")
    logger.info("connection remaps: %d table(s) -> %s", len(tables), path)
    return path


def write_stub(engine_root: Path) -> Path:
    """The zero-remap stub so the engine always compiles."""
    return write_remap_header(engine_root, [])
