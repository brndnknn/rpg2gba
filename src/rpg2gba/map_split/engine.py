"""Engine glue for split maps: the sibling table the map-name popup check reads
(`engine/src/rpg2gba_split_maps.c`, design §8). Written at assembly, always —
the zero-entry stub when nothing is split, so the engine's include compiles."""
from __future__ import annotations

import logging
from collections.abc import Iterable, Mapping
from pathlib import Path

from rpg2gba.map_split.ids import is_piece, origin_of

logger = logging.getLogger(__name__)

GEN_RELPATH = Path("src/data/rpg2gba_split_siblings.gen.h")
_GEN_HEADER = "// generated by rpg2gba (rpg2gba.map_split.engine) — do not edit\n"


def render_siblings_header(map_ids: Iterable[int], map_const_of: Mapping[int, str]) -> str:
    """The gen-header text for every split piece in `map_ids` (built maps only)."""
    pieces = sorted(int(m) for m in map_ids if is_piece(m))
    if not pieces:
        return (
            _GEN_HEADER
            + "#define RPG2GBA_SPLIT_SIBLING_COUNT 0\n"
            + "static const struct Rpg2gbaSplitSibling sRpg2gbaSplitSiblings[] = { {0} };\n"
        )
    missing = [m for m in pieces if m not in map_const_of]
    if missing:
        raise KeyError(f"split piece(s) {missing} have no minted MAP_* constant")
    lines = [_GEN_HEADER, f"#define RPG2GBA_SPLIT_SIBLING_COUNT {len(pieces)}\n",
             "static const struct Rpg2gbaSplitSibling sRpg2gbaSplitSiblings[] = {\n"]
    for m in pieces:
        c = map_const_of[m]
        lines.append(f"    {{ .mapGroup = MAP_GROUP({c}), .mapNum = MAP_NUM({c}), "
                     f".origin = {origin_of(m)} }},\n")
    lines.append("};\n")
    return "".join(lines)


def write_siblings_header(
    engine_root: Path, map_ids: Iterable[int], map_const_of: Mapping[int, str]
) -> Path:
    """(Over)write the gen header under `engine_root` (idempotent, byte-stable)."""
    path = Path(engine_root) / GEN_RELPATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_siblings_header(map_ids, map_const_of), encoding="utf-8")
    logger.info("split siblings -> %s", path)
    return path
