"""Render the generated move, ability and machine headers."""
from __future__ import annotations

import re

from rpg2gba.species_converter.stage import emit_engine_text
from rpg2gba.text_validator.engine_metrics import Charmap, measure_line_width_px, wrap_to_width

from .catalog import Catalog, GenAbility, GenMove

BANNER = "// Generated by rpg2gba (battle_converter). Do not edit.\n"

#: Widest line of any stock move description (moves_info.h, measured
#: 2026-10-19); the summary screen's box holds two lines.
MOVE_DESCRIPTION_WIDTH_PX = 152
MOVE_DESCRIPTION_LINES = 2
#: Widest stock ability description (abilities.h); the summary shows one line.
ABILITY_DESCRIPTION_WIDTH_PX = 146
MOVE_NAME_LENGTH = 16       # constants/global.h
ABILITY_NAME_LENGTH = 16    # constants/global.h


def text(s: str, chars: frozenset[str], label: str) -> str:
    return emit_engine_text(s, chars, species=label, field="text")


def move_description_lines(move: GenMove, charmap: Charmap) -> list[str]:
    """A ruling's rewrite keeps its own line breaks; Uranium's text is wrapped.
    Either must fit the box, or this fails loud (add a description ruling)."""
    label = f"{move.constant} description"
    if "\n" in move.description:
        lines = move.description.split("\n")
    else:
        lines = wrap_to_width(move.description, charmap,
                              width_px=MOVE_DESCRIPTION_WIDTH_PX, label=label)
    too_wide = [ln for ln in lines if measure_line_width_px(ln, charmap) > MOVE_DESCRIPTION_WIDTH_PX]
    if len(lines) > MOVE_DESCRIPTION_LINES or too_wide:
        raise ValueError(
            f"{label}: {len(lines)} lines {too_wide or ''} does not fit the "
            f"{MOVE_DESCRIPTION_LINES}x{MOVE_DESCRIPTION_WIDTH_PX}px box; add a description "
            "to its ruling in reference/battle_rulings.json")
    return lines


def ability_description(ability: GenAbility, charmap: Charmap) -> str:
    width = measure_line_width_px(ability.description, charmap)
    if width > ABILITY_DESCRIPTION_WIDTH_PX:
        raise ValueError(
            f"{ability.constant} description is {width}px, over the "
            f"{ABILITY_DESCRIPTION_WIDTH_PX}px line; add a description to its ruling")
    return ability.description


def _check_name(name: str, limit: int, label: str) -> None:
    if len(name) > limit:
        raise ValueError(f"{label}: name {name!r} exceeds {limit} characters")


def anim_script(stock_moves_info: str, move: str) -> str:
    """The battleAnimScript symbol of a stock move's gMovesInfo row."""
    start = re.search(rf"^    \[{re.escape(move)}\] =\n", stock_moves_info, re.M)
    if not start:
        raise ValueError(f"src/data/moves_info.h: no row for [{move}]")
    end = stock_moves_info.find("\n    },", start.end())
    m = re.search(r"\.battleAnimScript = (\w+),", stock_moves_info[start.end():end])
    if not m:
        raise ValueError(f"src/data/moves_info.h: [{move}] has no battleAnimScript")
    return m.group(1)


# --- constants ---------------------------------------------------------------

def render_move_constants(cat: Catalog) -> str:
    members = "".join(
        f" \\\n    {g.constant}{' = MOVES_COUNT_GEN9' if i == 0 else ''},"
        for i, g in enumerate(cat.moves))
    first = "" if cat.moves else " = MOVES_COUNT_GEN9"
    aliases = "".join(f"#define {g.constant} {g.alias_of}\n" for g in cat.aliases)
    has = "".join(f"#define RPG2GBA_HAS_{g.constant} 1\n" for g in cat.moves)
    return (
        BANNER
        + "// Included at the top of constants/moves.h (fenced RPG2GBA GAME PROFILE hook).\n"
        + f"#define RPG2GBA_GAME_MOVES{members} \\\n    RPG2GBA_MOVES_END{first},\n"
        + "// Moves the game spells differently from a stock move it equals.\n"
        + aliases
        + "// Generated moves, for engine C that names one (fenced, keyed on these).\n"
        + has
    )


def render_ability_constants(cat: Catalog) -> str:
    members = "".join(
        f" \\\n    {g.constant}{' = ABILITIES_COUNT_GEN9' if i == 0 else ''},"
        for i, g in enumerate(cat.abilities))
    first = "" if cat.abilities else " = ABILITIES_COUNT_GEN9"
    has = "".join(f"#define RPG2GBA_HAS_{g.constant} 1\n"
                  for g in cat.abilities if g.kind == "implemented")
    return (
        BANNER
        + "// Included at the top of constants/abilities.h (fenced RPG2GBA GAME PROFILE hook).\n"
        + f"#define RPG2GBA_GAME_ABILITIES{members} \\\n    RPG2GBA_ABILITIES_END{first},\n"
        + "// Abilities whose behaviour the engine implements (fenced C keyed on these).\n"
        + has
    )


_TMHM_ENTRY = re.compile(r"F\((\w+)\)")


def stock_machines(tms_hms_h: str) -> tuple[list[str], list[str]]:
    """Stock's TM and HM move lists (the `#else` branch of constants/tms_hms.h)."""
    tm_part, hm_part = tms_hms_h.split("#define FOREACH_HM(F)", 1)
    tm_part = tm_part.split("#define FOREACH_TM(F)", 1)[1]
    hm_part = hm_part.split("#define FOREACH_TMHM", 1)[0]
    return _TMHM_ENTRY.findall(tm_part), _TMHM_ENTRY.findall(hm_part)


def machine_aliases(kind: str, stock: list[str], game: tuple[str, ...]) -> list[str]:
    """`#define ITEM_HM_FLASH ITEM_HM05` for every stock move-named machine id the
    game's list no longer mints. Stock data and scripts key machines by those
    names (src/data/items.h rows `[ITEM_HM_FLASH] =`); the alias keeps them on
    the same machine number. A stock name the game's list mints for a different
    number would make two rows for one item, so that fails loud."""
    names = [m.removeprefix("MOVE_") for m in game]
    out = []
    for i, move in enumerate(stock, start=1):
        if move in names:
            if names.index(move) + 1 != i:
                raise ValueError(
                    f"stock {kind}{i:02d} ({move}) is the game's {kind}"
                    f"{names.index(move) + 1:02d}; stock rows keyed ITEM_{kind}_{move} would "
                    "duplicate that machine")
            continue
        out.append(f"#define ITEM_{kind}_{move} ITEM_{kind}{i:02d}\n")
    return out


def render_machines(cat: Catalog, stock_tms: list[str], stock_hms: list[str]) -> str:
    def body(moves: tuple[str, ...]) -> str:
        return " \\\n".join(f"    F({m.removeprefix('MOVE_')})" for m in moves)

    aliases = machine_aliases("TM", stock_tms, cat.tms) + machine_aliases("HM", stock_hms, cat.hms)
    return (
        BANNER
        + "// The game's TM/HM list; replaces stock's in constants/tms_hms.h (fenced\n"
        + "// RPG2GBA GAME PROFILE hook). TMnn / HMnn teach the nth entry.\n"
        + f"#define FOREACH_TM(F) \\\n{body(cat.tms)}\n\n"
        + f"#define FOREACH_HM(F) \\\n{body(cat.hms)}\n\n"
        + "// Stock's move-named machine ids the list above no longer mints, kept on\n"
        + "// their machine number (stock data and scripts use them).\n"
        + "".join(aliases)
    )


# --- table rows --------------------------------------------------------------

def _added_effect(move: GenMove, effect) -> str:
    parts = [f".moveEffect = {effect.move_effect}"]
    if effect.chance == "effect_chance":
        if move.effect_chance == 0:
            raise ValueError(
                f"{move.constant}: {effect.move_effect} rolls the move's effect chance, "
                "which is 0 -- Essentials never fires it; rule the move explicitly")
        parts.append(f".chance = {move.effect_chance}")
    elif effect.chance != "always":
        raise ValueError(f"{move.constant}: unknown chance {effect.chance!r}")
    if effect.self_:
        parts.append(".self = TRUE")
    parts += [f".{k} = {v}" for k, v in effect.extra]
    return "{\n            " + ",\n            ".join(parts) + ",\n        }"


def render_move_row(move: GenMove, charmap: Charmap, chars: frozenset[str],
                    stock_moves_info: str) -> str:
    _check_name(move.name, MOVE_NAME_LENGTH, move.constant)
    desc = move_description_lines(move, charmap)
    desc_c = "\n".join(
        f'            "{text(ln, chars, move.constant)}' + ('\\n"' if i < len(desc) - 1 else '"')
        for i, ln in enumerate(desc))
    spec = move.spec
    lines = [
        f"    [{move.constant}] =",
        "    {",
        f'        .name = COMPOUND_STRING("{text(move.name, chars, move.constant)}"),',
        f"        .description = COMPOUND_STRING(\n{desc_c}),",
        f"        .effect = {spec.effect},",
        f"        .power = {move.power},",
        f"        .type = {move.type_},",
        f"        .accuracy = {move.accuracy},",
        f"        .pp = {move.pp},",
        f"        .target = {move.target},",
        f"        .priority = {move.priority},",
        f"        .category = {move.category},",
    ]
    lines += list(move.flag_lines)
    if spec.argument:
        lines.append(f"        .argument = {{ {spec.argument} }},")
    lines += [f"        .{k} = {v}," for k, v in spec.fields]
    if spec.added:
        effects = ", ".join(_added_effect(move, e) for e in spec.added)
        lines.append(f"        .additionalEffects = ADDITIONAL_EFFECTS({effects}),")
    lines.append(f"        .battleAnimScript = {anim_script(stock_moves_info, move.anim)},")
    lines.append("    },")
    return "\n".join(lines)


def render_moves_info(cat: Catalog, charmap: Charmap, chars: frozenset[str],
                      stock_moves_info: str) -> str:
    rows = [render_move_row(g, charmap, chars, stock_moves_info) for g in cat.moves]
    return BANNER + "// Rows of gMovesInfo (src/data/moves_info.h).\n\n" + "\n\n".join(rows) + "\n"


def render_abilities_info(cat: Catalog, charmap: Charmap, chars: frozenset[str]) -> str:
    rows = []
    for g in cat.abilities:
        _check_name(g.name, ABILITY_NAME_LENGTH, g.constant)
        row = [f"    [{g.constant}] =", "    {",
               f'        .name = _("{text(g.name, chars, g.constant)}"),',
               f'        .description = COMPOUND_STRING('
               f'"{text(ability_description(g, charmap), chars, g.constant)}"),']
        if g.breakable:
            row.append("        .breakable = TRUE,")
        row.append("    },")
        rows.append("\n".join(row))
    return (BANNER + "// Rows of gAbilitiesInfo (src/data/abilities.h).\n\n"
            + "\n\n".join(rows) + "\n")
