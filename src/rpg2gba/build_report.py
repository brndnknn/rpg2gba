"""Per-build report: what the converted game kept and dropped from stock, and ROM use.

Reads the linker map of the last engine build plus the game profile sidecars
the assembler wrote, and writes `<output>/uranium-build/rom_report.md`. Run it
after `make modern`:

    python -m rpg2gba.build_report

The report is how the operator sees what is in the ROM without reading a
stripped source tree (reference/engine_layers_i3_i5.md §6, decision 2026-10-19).
"""
from __future__ import annotations

import json
import logging
import os
import re
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import click

logger = logging.getLogger(__name__)

ROM_BASE = 0x08000000
ROM_LIMIT = 32 * 1024 * 1024
_ROM_END = re.compile(r"^\s*0x([0-9a-f]+)\s+__rom_end\b", re.MULTILINE)
_SECTION_LINE = re.compile(r"^\s*(?:\S+)?\s+0x([0-9a-f]{8,16})\s+0x([0-9a-f]+)\s+(\S+\.o)\s*$")
_STUB_LAYOUT_DIR = "UraniumWalkerStub"


@dataclass(frozen=True)
class RomUsage:
    used: int
    by_object: dict[str, int]

    @property
    def free(self) -> int:
        return ROM_LIMIT - self.used


def read_rom_usage(map_path: Path) -> RomUsage:
    """ROM bytes in use (`__rom_end`) and ROM bytes per object file, from an ld map."""
    text = Path(map_path).read_text(encoding="utf-8", errors="replace")
    m = _ROM_END.search(text)
    if not m:
        raise ValueError(f"{map_path}: no __rom_end symbol; is this a pokeemerald link map?")
    by_object: dict[str, int] = defaultdict(int)
    for line in text.splitlines():
        s = _SECTION_LINE.match(line)
        if not s:
            continue
        addr, size = int(s.group(1), 16), int(s.group(2), 16)
        if ROM_BASE <= addr < ROM_BASE + ROM_LIMIT and size:
            by_object[s.group(3).removeprefix("build/emerald/")] += size
    return RomUsage(int(m.group(1), 16) - ROM_BASE, dict(by_object))


def count_stubbed_layouts(layouts_gen_json: Path) -> tuple[int, int]:
    """(stubbed stock layouts, total layouts) in the generated layouts overlay."""
    data = json.loads(Path(layouts_gen_json).read_text(encoding="utf-8"))
    layouts = [e for e in data.get("layouts", []) if "blockdata_filepath" in e]
    stubbed = sum(1 for e in layouts if f"/{_STUB_LAYOUT_DIR}/" in e["blockdata_filepath"])
    return stubbed, len(layouts)


def _mib(n: int) -> str:
    return f"{n / 2**20:.2f} MiB"


def render(usage: RomUsage, profile: dict | None, layouts: tuple[int, int] | None,
           top: int = 15) -> str:
    lines = [
        "# ROM report",
        "",
        "Generated by `python -m rpg2gba.build_report` from the last engine build.",
        "",
        f"**ROM used: {usage.used:,} B ({_mib(usage.used)}) of 32 MiB "
        f"({100 * usage.used / ROM_LIMIT:.1f}%); free {_mib(usage.free)}.**",
        "",
        "## Stock content",
        "",
    ]
    if profile is None:
        lines.append("- Species profile: **none** (every stock species family is compiled in).")
    else:
        lines.append(
            f"- Species families: kept **{len(profile['keep'])}**, dropped "
            f"**{len(profile['drop'])}**."
        )
        lines.append(
            "- Kept because the game uses " + ", ".join(profile["used_species"]) + "."
        )
        lines.append("- Kept families: " + ", ".join(profile["keep"]) + ".")
    if layouts is None:
        lines.append("- Stock map layouts: no layouts overlay found.")
    else:
        stubbed, total = layouts
        lines.append(f"- Map layouts: {stubbed} stock layouts stubbed, "
                     f"{total - stubbed} shipped (of {total}).")
    lines += ["", f"## Largest {top} objects", "", "| Object | Bytes |", "|---|---|"]
    for obj, size in sorted(usage.by_object.items(), key=lambda kv: -kv[1])[:top]:
        lines.append(f"| `{obj}` | {size:,} |")
    return "\n".join(lines) + "\n"


def write_report(engine: Path, out: Path) -> Path:
    usage = read_rom_usage(engine / "pokeemerald.map")
    profile_path = out / "species" / "species_profile.json"
    profile = (json.loads(profile_path.read_text(encoding="utf-8"))
               if profile_path.is_file() else None)
    layouts_path = engine / "data" / "layouts" / "layouts.gen.json"
    layouts = count_stubbed_layouts(layouts_path) if layouts_path.is_file() else None
    dest = out / "rom_report.md"
    dest.write_text(render(usage, profile, layouts), encoding="utf-8")
    logger.info("ROM used %s of 32 MiB (free %s); report: %s",
                _mib(usage.used), _mib(usage.free), dest)
    return dest


@click.command()
@click.option("--engine", type=click.Path(file_okay=False, path_type=Path), default=None,
              help="Engine build dir (default: $RPG2GBA_POKEEMERALD).")
@click.option("--output", type=click.Path(file_okay=False, path_type=Path), default=None,
              help="Build output dir (default: $RPG2GBA_OUTPUT/uranium-build).")
def main(engine: Path | None, output: Path | None) -> None:
    """Write the per-build ROM report."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    from rpg2gba.pipeline import _load_dotenv  # noqa: PLC0415

    _load_dotenv()
    engine = engine or Path(os.environ["RPG2GBA_POKEEMERALD"])
    output = output or Path(os.environ.get("RPG2GBA_OUTPUT", "output")) / "uranium-build"
    dest = write_report(engine, output)
    click.echo(dest.read_text(encoding="utf-8").split("\n\n")[2])


if __name__ == "__main__":
    main()
