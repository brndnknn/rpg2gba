"""Render the generated item headers.

Clones copy the analog's stock initializer block field by field and replace only
what differs (name, description, price, icon, effect), so a berry or medicine
behaves exactly like its stock twin.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from rpg2gba.species_converter.stage import emit_engine_text
from rpg2gba.text_validator.engine_metrics import Charmap, measure_line_width_px, wrap_to_width

from .catalog import Catalog, GenItem

BANNER = "// Generated by rpg2gba (item_converter). Do not edit.\n"

#: Widest line in any stock bag description (measured 2026-10-19 over 718
#: stock entries). Longer text pages on R in the bag (item_menu.c).
DESCRIPTION_WIDTH_PX = 102
DESCRIPTION_PAGE_LINES = 3
#: In a description that needs more than one page, the last line of each page
#: wraps narrower: the bag draws a 16px R-button mark at x=96 there (item_menu.c).
PAGED_DESCRIPTION_WIDTH_PX = 92
DESCRIPTION_MAX_LINES = 12  # four pages; a sanity bound, not a design limit
#: Berry tag lines: the widest stock description1/2 (berry.c), two lines.
BERRY_TAG_WIDTH_PX = 203
BERRY_NAME_LENGTH = 6       # global.berry.h
ITEM_NAME_LENGTH = 20       # constants/global.h

_POCKETS: dict[int, str] = {
    1: "POCKET_ITEMS", 2: "POCKET_ITEMS", 3: "POCKET_POKE_BALLS", 4: "POCKET_TM_HM",
    5: "POCKET_BERRIES", 6: "POCKET_ITEMS", 7: "POCKET_ITEMS", 8: "POCKET_KEY_ITEMS",
}


def stem(item: GenItem) -> str:
    """Asset file stem: ITEM_ACAI_BERRY -> acai_berry."""
    return item.constant.removeprefix("ITEM_").lower()


def berry_short_name(item: GenItem) -> str:
    name = item.name.removesuffix(" Berry")
    if len(name) > BERRY_NAME_LENGTH:
        raise ValueError(f"{item.constant}: berry name {name!r} exceeds {BERRY_NAME_LENGTH}")
    return name


# --- stock block extraction --------------------------------------------------

@dataclass
class Block:
    """One `[KEY] = { ... },` initializer, split into field chunks in order."""
    fields: list[tuple[str, str]]   # (field name, full chunk text incl. indentation)

    def get(self, name: str) -> str:
        for f, chunk in self.fields:
            if f == name:
                return chunk
        raise KeyError(name)

    def render(self, key: str, replace: dict[str, str | None]) -> str:
        """Re-emit under `key`; `replace` maps field -> new value text (None drops it).
        Replaced fields that the block lacks are appended."""
        out = [f"    [{key}] =", "    {"]
        seen: set[str] = set()
        for f, chunk in self.fields:
            if f in replace:
                seen.add(f)
                if replace[f] is not None:
                    out.append(f"        .{f} = {replace[f]},")
            else:
                out.append(chunk)
        for f, value in replace.items():
            if f not in seen and value is not None:
                out.append(f"        .{f} = {value},")
        out.append("    },")
        return "\n".join(out)


_FIELD_START = re.compile(r"^        \.(\w+) =")


def extract_block(text: str, key: str, source: str) -> Block:
    m = re.search(rf"^    \[{re.escape(key)}\] =\n    \{{\n(.*?)\n    \}},", text, re.M | re.S)
    if not m:
        raise ValueError(f"{source}: no stock initializer for [{key}]")
    body = m.group(1).split("\n")
    if any(line.lstrip().startswith("#") for line in body):
        raise ValueError(f"{source}: [{key}] has preprocessor lines; cannot clone it safely")
    fields: list[tuple[str, list[str]]] = []
    for line in body:
        fm = _FIELD_START.match(line)
        if fm:
            fields.append((fm.group(1), [line]))
        elif fields:
            fields[-1][1].append(line)
        else:
            raise ValueError(f"{source}: [{key}] starts with a non-field line {line!r}")
    return Block([(f, "\n".join(lines)) for f, lines in fields])


def table_text(text: str, table: str, source: str) -> str:
    """The initializer of the array named `table`, from its name to the closing `};`."""
    start = re.search(rf"\b{re.escape(table)}\[[^\]]*\]\s*=\s*\{{", text)
    if not start:
        raise ValueError(f"{source}: no table {table}")
    end = text.find("\n};", start.end())
    if end < 0:
        raise ValueError(f"{source}: table {table} is not closed")
    return text[start.end():end]


def _row_value(text: str, key: str, source: str) -> str:
    """Right-hand side of a one-line `[KEY] = value,` table row."""
    m = re.search(rf"^[ \t]*\[{re.escape(key)}\][ \t]*=[ \t]*(\S.*?)[ \t]*,?[ \t]*$", text, re.M)
    if not m:
        raise ValueError(f"{source}: no one-line row for [{key}]")
    return m.group(1).rstrip(",").rstrip()


# --- text --------------------------------------------------------------------

def text(s: str, chars: frozenset[str], label: str) -> str:
    """`s` escaped for a C literal that tools/preproc re-encodes via charmap.txt:
    non-ASCII stays literal and must have a glyph (fails loud otherwise)."""
    return emit_engine_text(s, chars, species=label, field="text")


def compound_string(lines: list[str], chars: frozenset[str], label: str,
                    indent: str = "            ") -> str:
    if not lines:
        return 'COMPOUND_STRING("")'
    parts = [f'{indent}"{text(ln, chars, label)}' + ('\\n"' if i < len(lines) - 1 else '"')
             for i, ln in enumerate(lines)]
    return "COMPOUND_STRING(\n" + "\n".join(parts) + ")"


def wrap_paged(text_in: str, charmap: Charmap, label: str) -> list[str]:
    """Greedy wrap where the last line of every 3-line page is narrower, leaving
    the corner the bag's R-button mark is drawn in. A word too wide for that
    line moves to the next page, leaving the line empty."""
    lines: list[str] = []
    current = ""
    for word in text_in.split():
        while True:
            narrow = len(lines) % DESCRIPTION_PAGE_LINES == DESCRIPTION_PAGE_LINES - 1
            width = PAGED_DESCRIPTION_WIDTH_PX if narrow else DESCRIPTION_WIDTH_PX
            candidate = f"{current} {word}" if current else word
            if measure_line_width_px(candidate, charmap) <= width:
                current = candidate
                break
            if not current and not narrow:
                raise ValueError(
                    f"{label}: the word {word!r} is wider than the "
                    f"{DESCRIPTION_WIDTH_PX}px line budget -- no wrap point exists")
            lines.append(current)
            current = ""
    if current:
        lines.append(current)
    if len(lines) > DESCRIPTION_MAX_LINES:
        raise ValueError(f"{label}: wraps to {len(lines)} lines, over {DESCRIPTION_MAX_LINES}")
    return lines


def description_lines(item: GenItem, charmap: Charmap) -> list[str]:
    label = f"{item.constant} description"
    lines = wrap_to_width(item.description, charmap, width_px=DESCRIPTION_WIDTH_PX, label=label)
    if len(lines) <= DESCRIPTION_PAGE_LINES:
        return lines
    return wrap_paged(item.description, charmap, label)


def item_name(item: GenItem, chars: frozenset[str]) -> str:
    if len(item.name) > ITEM_NAME_LENGTH:
        raise ValueError(
            f"{item.constant}: name {item.name!r} exceeds {ITEM_NAME_LENGTH} characters; "
            "add a display_name to reference/item_rulings.json"
        )
    return f'ITEM_NAME("{text(item.name, chars, item.constant)}")'


# --- renderers ---------------------------------------------------------------

def render_constants(cat: Catalog) -> str:
    def members(items: tuple[GenItem, ...]) -> str:
        return "".join(f" \\\n    {g.constant}," for g in items)

    return (
        BANNER
        + "// Included at the top of constants/items.h (fenced RPG2GBA GAME PROFILE hook).\n"
        + f"#define RPG2GBA_EXTRA_BERRIES {len(cat.berries)}\n"
        + f"#define RPG2GBA_BERRY_ITEMS{members(cat.berries)}\n"
        + f"#define RPG2GBA_TAIL_ITEMS{members(cat.tail)}\n"
    )


def _icon_refs(item: GenItem, has_icon: bool) -> tuple[str, str]:
    if not has_icon:
        return "gItemIcon_QuestionMark", "gItemIconPalette_QuestionMark"
    return f"gItemIcon_Game{item.ident}", f"gItemIconPalette_Game{item.ident}"


def render_item_info(item: GenItem, desc: str, has_icon: bool, stock_items: str,
                     chars: frozenset[str]) -> str:
    icon, pal = _icon_refs(item, has_icon)
    common = {"name": item_name(item, chars), "description": desc, "price": str(item.price),
              "iconPic": icon, "iconPalette": pal}
    if item.kind == "berry":
        block = extract_block(stock_items, item.analog, "src/data/items.h")
        plural = item.name[:-len("Berry")] + "Berries" if item.name.endswith("Berry") else None
        common["pluralName"] = (f'ITEM_PLURAL_NAME("{text(plural, chars, item.constant)}")'
                                if plural else None)
        return block.render(item.constant, common)
    if item.kind == "heal":
        block = extract_block(stock_items, item.analog, "src/data/items.h")
        common["effect"] = f"gItemEffect_Game{item.ident}"
        common["holdEffectParam"] = str(item.heal_hp)
        return block.render(item.constant, common)
    lines = [f"    [{item.constant}] =", "    {",
             f"        .name = {common['name']},",
             f"        .price = {item.price},",
             f"        .description = {desc},"]
    if item.kind == "key":
        lines += ["        .importance = 1,", "        .pocket = POCKET_KEY_ITEMS,"]
    else:
        sort = {"inert": "ITEM_TYPE_SELLABLE", "held": "ITEM_TYPE_HELD_ITEM"}[item.kind]
        lines += [f"        .pocket = {_POCKETS[item.essentials_pocket]},",
                  f"        .sortType = {sort},"]
    lines += ["        .type = ITEM_USE_BAG_MENU,",
              "        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,",
              f"        .iconPic = {icon},",
              f"        .iconPalette = {pal},",
              "    },"]
    return "\n".join(lines)


def render_items_info(cat: Catalog, charmap: Charmap, chars: frozenset[str],
                      has_icon: dict[str, bool], stock_items: str) -> str:
    entries = []
    for item in cat.generated:
        desc = compound_string(description_lines(item, charmap), chars, item.constant)
        entries.append(render_item_info(item, desc, has_icon[item.constant], stock_items, chars))
    return BANNER + "// Rows of gItemsInfo (src/data/items.h).\n\n" + "\n\n".join(entries) + "\n"


def render_item_effects(cat: Catalog) -> str:
    out = [BANNER, "// Composed item effects (src/data/pokemon/item_effects.h).\n"]
    for item in cat.generated:
        if item.kind != "heal":
            continue
        fields = []
        if item.cure_status:
            fields.append("    [3] = ITEM3_STATUS_ALL,")
        fields += ["    [4] = ITEM4_HEAL_HP,", f"    [6] = {item.heal_hp}, // HP recovered"]
        out.append(f"\nconst u8 gItemEffect_Game{item.ident}[7] = {{\n" + "\n".join(fields) + "\n};\n")
    return "".join(out)


def _berry_key(const: str) -> str:
    return f"{const} - FIRST_BERRY_INDEX"


def render_berries(cat: Catalog, charmap: Charmap, chars: frozenset[str],
                   stock_berry_c: str) -> str:
    entries = []
    for item in cat.berries:
        block = extract_block(stock_berry_c, _berry_key(item.analog), "src/berry.c")
        tag = wrap_to_width(item.description, charmap, width_px=BERRY_TAG_WIDTH_PX,
                            max_lines=2, label=f"{item.constant} berry tag")
        tag += [""] * (2 - len(tag))
        c = item.constant
        entries.append(block.render(_berry_key(c), {
            "name": f'_("{text(berry_short_name(item), chars, c)}")',
            "description1": f'COMPOUND_STRING("{text(tag[0], chars, c)}")',
            "description2": f'COMPOUND_STRING("{text(tag[1], chars, c)}")',
        }))
    return BANNER + "// Rows of gBerries (src/berry.c).\n\n" + "\n\n".join(entries) + "\n"


def render_berry_rows(cat: Catalog, stock_text: str, table: str, source: str) -> str:
    """Rows of a berry-indexed table, each copied from the analog's row."""
    body = table_text(stock_text, table, source)
    rows = [f"    [{_berry_key(item.constant)}] = "
            f"{_row_value(body, _berry_key(item.analog), source)},"
            for item in cat.berries]
    return BANNER + f"// Rows of {table} ({source}).\n" + "\n".join(rows) + "\n"


def render_berry_pics(cat: Catalog) -> str:
    rows = [f"    [ITEM_TO_BERRY({g.constant}) - 1] = "
            f"{{gBerryPic_Game{g.ident}, gBerryPalette_Game{g.ident}}},"
            for g in cat.berries]
    return BANNER + "// Rows of sBerryPicTable (src/item_menu_icons.c).\n" + "\n".join(rows) + "\n"


def render_graphics(cat: Catalog, has_icon: dict[str, bool]) -> tuple[str, str]:
    """(externs for include/graphics.h, definitions for src/graphics.c)."""
    ext = [BANNER]
    defs = [BANNER]
    for item in cat.generated:
        if not has_icon[item.constant]:
            continue
        s = stem(item)
        ext += [f"extern const u32 gItemIcon_Game{item.ident}[];\n",
                f"extern const u16 gItemIconPalette_Game{item.ident}[];\n"]
        defs += [f'const u32 gItemIcon_Game{item.ident}[] = '
                 f'INCGFX_U32("graphics/items/rpg2gba/{s}.png", ".4bpp.smol");\n',
                 f'const u16 gItemIconPalette_Game{item.ident}[] = '
                 f'INCGFX_U16("graphics/items/rpg2gba/{s}.pal", ".gbapal");\n']
    for item in cat.berries:
        s = stem(item)
        ext += [f"extern const u32 gBerryPic_Game{item.ident}[];\n",
                f"extern const u16 gBerryPalette_Game{item.ident}[];\n"]
        defs += [f'const u32 gBerryPic_Game{item.ident}[] = '
                 f'INCGFX_U32("graphics/berries/rpg2gba/{s}.png", ".4bpp.smol");\n',
                 f'const u16 gBerryPalette_Game{item.ident}[] = '
                 f'INCGFX_U16("graphics/berries/rpg2gba/{s}.png", ".gbapal");\n']
    return "".join(ext), "".join(defs)


def stock_sources(fork: Path) -> dict[str, str]:
    fork = Path(fork)
    return {
        "items": (fork / "src/data/items.h").read_text(encoding="utf-8"),
        "berry_c": (fork / "src/berry.c").read_text(encoding="utf-8"),
        "trees": (fork / "src/data/object_events/berry_tree_graphics_tables.h").read_text(
            encoding="utf-8"),
    }
