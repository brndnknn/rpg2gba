"""Bag pocket sizes and SaveBlock1 secret-base capacity, generated per game.

The right pocket size is "how many distinct item kinds of this game can sit in
that pocket". That is the game's *own* item list (Uranium's `items.dat`, mapped
through `_POCKET_BY_ESSENTIALS`): stock items the game never hands out are
unreachable and do not count. A pocket never shrinks below the stock size.
"""
from __future__ import annotations

import logging
from collections.abc import Iterable
from pathlib import Path

from rpg2gba.pbs_converter import items as pbs_items

logger = logging.getLogger(__name__)

BAG_H = Path("include/constants/rpg2gba_bag.gen.h")

#: Stock sizes (engine/include/constants/global.h).
STOCK_KEYITEMS = 30
STOCK_TMHM = 64
STOCK_SECRET_BASES = 20
#: sizeof(struct SecretBase) and bytes per bag slot (struct ItemSlot).
SECRET_BASE_BYTES = 160
SLOT_BYTES = 4

#: This game has no secret bases (profile decision, not detected).
GAME_SECRET_BASES = 1


def pocket_kind_counts(records: Iterable[pbs_items.Item]) -> dict[str, int]:
    """Distinct item kinds per fork pocket (POCKET_*) over the game's records."""
    counts: dict[str, int] = {}
    for rec in records:
        pocket = pbs_items._POCKET_BY_ESSENTIALS[rec.pocket]
        counts[pocket] = counts.get(pocket, 0) + 1
    return counts


def pocket_sizes(counts: dict[str, int]) -> tuple[int, int]:
    """(key items, TM/HM) sizes: max(stock, game kind count)."""
    return (max(STOCK_KEYITEMS, counts.get("POCKET_KEY_ITEMS", 0)),
            max(STOCK_TMHM, counts.get("POCKET_TM_HM", 0)))


def save_delta_bytes(keyitems: int, tmhm: int, secret_bases: int) -> int:
    """Informational SaveBlock1 growth estimate (negative = shrink)."""
    return ((keyitems - STOCK_KEYITEMS) + (tmhm - STOCK_TMHM)) * SLOT_BYTES \
        - (STOCK_SECRET_BASES - secret_bases) * SECRET_BASE_BYTES


def render_bag(keyitems: int, tmhm: int, *, secret_bases: int) -> str:
    """Plain integer #defines only: constants/global.h includes this very early."""
    if secret_bases < 1:
        raise ValueError("secret_bases must be >= 1 (index 0 is the player's own base)")
    return (
        "// Generated by rpg2gba (item_converter.bag) -- do not edit.\n"
        "// Bag pocket sizes = max(stock, the game's own item kinds per pocket);\n"
        "// secret-base capacity is a profile decision (the game has none).\n"
        "#ifndef GUARD_RPG2GBA_BAG_GEN_H\n"
        "#define GUARD_RPG2GBA_BAG_GEN_H\n"
        f"#define RPG2GBA_BAG_KEYITEMS_COUNT {keyitems}\n"
        f"#define RPG2GBA_BAG_TMHM_COUNT {tmhm}\n"
        f"#define RPG2GBA_SECRET_BASES_COUNT {secret_bases}\n"
        "#endif\n"
    )


def render_for_game(uranium_src: Path, *, secret_bases: int = GAME_SECRET_BASES) -> str:
    records = pbs_items.parse(Path(uranium_src) / "Data" / "items.dat")
    keyitems, tmhm = pocket_sizes(pocket_kind_counts(records))
    logger.info("  bag: key items %d, TM/HM %d, secret bases %d; SaveBlock1 delta ~%+d bytes",
                keyitems, tmhm, secret_bases, save_delta_bytes(keyitems, tmhm, secret_bases))
    return render_bag(keyitems, tmhm, secret_bases=secret_bases)
